#!/usr/bin/env python3
"""Raw-time validation for the remaining global spoofing screens.

The broad screens are generated by ``search_remaining_spoofing_modes.py``.
This program fetches only observations or members belonging to their finite
candidate sets.  Remote ClickHouse access goes through ``ch_remote.py`` and is
therefore forced to ``readonly=2``.
"""

