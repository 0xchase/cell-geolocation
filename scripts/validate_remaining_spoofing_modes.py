import numpy as np
import pandas as pd

from ch_remote import ch_df


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "data" / "spoofing" / "remaining_search"
KEY = ["mcc", "mnc", "lac", "cid", "cell_type"]
EARTH_KM = 6371.0088


def haversine(lat1, lon1, lat2, lon2):
    lat1 = np.radians(np.asarray(lat1, dtype=float))
    lon1 = np.radians(np.asarray(lon1, dtype=float))
    lat2 = np.radians(np.asarray(lat2, dtype=float))
    lon2 = np.radians(np.asarray(lon2, dtype=float))
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = np.sin(dlat / 2) ** 2 + np.cos(lat1) * np.cos(lat2) * np.sin(dlon / 2) ** 2
    return 2 * EARTH_KM * np.arctan2(np.sqrt(a), np.sqrt(np.maximum(1 - a, 0)))


def normalize_headers(frame: pd.DataFrame) -> pd.DataFrame:
    frame = frame.copy()
    frame.columns = [column.rsplit(".", 1)[-1] for column in frame.columns]
    return frame


def identity_tuples(frame: pd.DataFrame) -> str:
    return ",".join(
        f"({int(r.mcc)},{int(r.mnc)},{int(r.lac)},{int(r.cid)},'{r.cell_type}')"
        for r in frame[KEY].drop_duplicates().itertuples(index=False)
    )


def uid(frame: pd.DataFrame) -> pd.Series:
    return frame[KEY].astype(str).agg("/".join, axis=1)


def candidate_identities() -> pd.DataFrame:
    moving = pd.read_csv(OUTPUT / "moving_track_audit.csv")
    moving = moving[moving["passes_geometry"]].copy()
    moving["moving_candidate"] = True
    cycling = pd.read_csv(OUTPUT / "multidestination_identity_audit.csv")
    cycling = cycling[cycling["cycle_candidate"]].copy()
    cycling["cycling_candidate"] = True
    kinematic = normalize_headers(pd.read_csv(OUTPUT / "kinematic_interval_screen.csv"))
    kinematic = kinematic[KEY].drop_duplicates()
    kinematic["kinematic_candidate"] = True
    merged = moving[KEY + ["moving_candidate"]].merge(
        cycling[KEY + ["cycling_candidate"]], on=KEY, how="outer"
    ).merge(kinematic, on=KEY, how="outer")
    for column in ["moving_candidate", "cycling_candidate", "kinematic_candidate"]:
        merged[column] = merged[column].fillna(False).astype(bool)
    return merged


def fetch_raw(ids: pd.DataFrame, chunk_size: int = 150) -> pd.DataFrame:
    frames = []
    for start in range(0, len(ids), chunk_size):
        chunk = ids.iloc[start:start + chunk_size]
        print(f"raw observations: identities {start + 1}-{start + len(chunk)} of {len(ids)}", flush=True)
        tuples = identity_tuples(chunk)
        frame = ch_df(f"""
          SELECT mcc,mnc,lac,cid,toString(cell_type) AS cell_type,
                 timestamp,lat,lon
          FROM cell.geos
          PREWHERE (mcc,mnc,lac,cid,cell_type) IN ({tuples})
          WHERE lat BETWEEN -90 AND 90 AND lon BETWEEN -180 AND 180
            AND NOT(abs(lat)<=0.01 AND abs(lon)<=0.01)
          ORDER BY mcc,mnc,lac,cid,cell_type,timestamp
        """, settings={"max_threads": 4, "max_execution_time": 3600})
        frames.append(normalize_headers(frame))
    raw = pd.concat(frames, ignore_index=True)
    raw["timestamp"] = pd.to_datetime(raw["timestamp"])
    raw["plat"] = np.rint(raw["lat"] * 100).astype(int)
    raw["plon"] = np.rint(raw["lon"] * 100).astype(int)
    return raw


