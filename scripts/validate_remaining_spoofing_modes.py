def raw_membership_pair_audit(
    raw: pd.DataFrame, members: pd.DataFrame, event_key: list[str],
    target_lat: str, target_lon: str, target_scale: float, prefix: str,
) -> pd.DataFrame:
    raw_groups = {key: group.sort_values("timestamp") for key, group in raw.groupby(KEY, sort=False)}
    rows = []
    for member in members.itertuples(index=False):
        identity = tuple(getattr(member, column) for column in KEY)
        group = raw_groups.get(identity)
        if group is None:
            continue
        ref_lat = member.hlat / 100 if hasattr(member, "hlat") else member.rlat / 100
        ref_lon = member.hlon / 100 if hasattr(member, "hlon") else member.rlon / 100
        destination_lat = getattr(member, target_lat) / target_scale
        destination_lon = getattr(member, target_lon) / target_scale
        home_distance = haversine(group.lat, group.lon, ref_lat, ref_lon)
        destination_distance = haversine(group.lat, group.lon, destination_lat, destination_lon)
        # Keep the two classes disjoint.  This matters below roughly 10 km:
        # otherwise one point inside overlapping radii can pair with itself and
        # masquerade as an exact dual-location observation.
        home = group[(home_distance <= 5) & (destination_distance > 1.5)]
        away = group[(destination_distance <= 1.5) & (home_distance > 5)]
        if home.empty or away.empty:
            continue
        home_seconds = home.timestamp.values.astype("datetime64[s]").astype("int64")
        away_seconds = away.timestamp.values.astype("datetime64[s]").astype("int64")
        nearest, gaps = nearest_indices(away_seconds, home_seconds)
        rows.append({column: getattr(member, column) for column in [*event_key, *KEY]} | {
            "home_raw_observations": len(home), "away_raw_observations": len(away),
            "minimum_home_away_gap_seconds": int(gaps.min()),
            "home_away_pairs_within_5m": int((gaps <= 300).sum()),
            "home_away_pairs_within_1h": int((gaps <= 3600).sum()),
            "exact_simultaneous": bool(np.any(gaps == 0)),
        })
    membership = pd.DataFrame(rows)
    membership.to_csv(OUTPUT / f"{prefix}_raw_membership_audit.csv", index=False)
    if membership.empty:
        event_audit = pd.DataFrame()
    else:
        event_audit = membership.groupby(event_key, as_index=False).agg(
            identities_with_raw_support=("cid", "size"),
            identities_with_pair_within_5m=("home_away_pairs_within_5m", lambda x: int((x > 0).sum())),
            identities_with_pair_within_1h=("home_away_pairs_within_1h", lambda x: int((x > 0).sum())),
            raw_home_observations=("home_raw_observations", "sum"),
            raw_away_observations=("away_raw_observations", "sum"),
            minimum_gap_seconds=("minimum_home_away_gap_seconds", "min"),
            exact_simultaneous_identities=("exact_simultaneous", "sum"),
        )
        event_audit["five_minute_pair_fraction"] = (
            event_audit.identities_with_pair_within_5m / event_audit.identities_with_raw_support
        )
        event_audit["one_hour_pair_fraction"] = (
            event_audit.identities_with_pair_within_1h / event_audit.identities_with_raw_support
        )
    event_audit.to_csv(OUTPUT / f"{prefix}_raw_event_audit.csv", index=False)
    return event_audit


def nearest_indices(left_seconds: np.ndarray, right_seconds: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    index = np.searchsorted(right_seconds, left_seconds)
    lo = np.clip(index - 1, 0, len(right_seconds) - 1)
    hi = np.clip(index, 0, len(right_seconds) - 1)
    nearest = np.where(
        np.abs(right_seconds[lo] - left_seconds) <= np.abs(right_seconds[hi] - left_seconds),
        lo, hi,
    )
    return nearest, np.abs(right_seconds[nearest] - left_seconds)


def validate_kinematics(raw: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    targets = normalize_headers(pd.read_csv(
        OUTPUT / "kinematic_interval_screen.csv",
        parse_dates=["away_first", "away_last", "home_first", "home_last"],
    ))
    raw_groups = {key: group.sort_values("timestamp") for key, group in raw.groupby(KEY, sort=False)}
    audits, pairs = [], []
    for row in targets.itertuples(index=False):
        key = tuple(getattr(row, column) for column in KEY)
        group = raw_groups.get(key)
        if group is None:
            continue
        home_distance = haversine(group.lat, group.lon, row.hlat / 100, row.hlon / 100)
        home = group[home_distance <= 5].copy()
        away = group[(group.plat == row.plat) & (group.plon == row.plon)].copy()
        if home.empty or away.empty:
            continue
        home_seconds = home.timestamp.values.astype("datetime64[s]").astype("int64")
        away_seconds = away.timestamp.values.astype("datetime64[s]").astype("int64")
        nearest, gaps = nearest_indices(away_seconds, home_seconds)
        speed = np.where(gaps == 0, np.inf, row.km / (gaps / 3600))
        qualifying = (gaps <= 3600) & (speed >= 900)
        for away_i in np.flatnonzero(qualifying):
            a = away.iloc[away_i]
            h = home.iloc[nearest[away_i]]
            pairs.append(dict(zip(KEY, key, strict=True)) | {
                "destination_lat": row.plat / 100, "destination_lon": row.plon / 100,
                "distance_km": row.km, "home_timestamp": h.timestamp,
                "away_timestamp": a.timestamp, "gap_seconds": int(gaps[away_i]),
                "implied_speed_kmh": float(speed[away_i]),
                "home_lat": h.lat, "home_lon": h.lon,
                "away_lat": a.lat, "away_lon": a.lon,
            })
        audits.append(dict(zip(KEY, key, strict=True)) | {
            "destination_lat": row.plat / 100, "destination_lon": row.plon / 100,
            "distance_km": row.km, "home_raw_observations": len(home),
            "away_raw_observations": len(away), "min_gap_seconds": int(gaps.min()),
            "max_implied_speed_kmh": float(np.max(speed)),
            "exact_simultaneous": bool(np.any(gaps == 0)),
            "impossible_pair_observations": int(qualifying.sum()),
            "impossible_pair_days": int(away.iloc[np.flatnonzero(qualifying)].timestamp.dt.date.nunique()),
        })
    audit = pd.DataFrame(audits)
    if not audit.empty:
        audit["raw_kinematic_positive"] = (
            audit["impossible_pair_observations"].ge(1)
            & (audit["exact_simultaneous"] | audit["impossible_pair_days"].ge(2))
        )
        audit = audit.sort_values(
            ["raw_kinematic_positive", "impossible_pair_days", "impossible_pair_observations", "distance_km"],
            ascending=False,
        )
    pair_frame = pd.DataFrame(pairs)
    audit.to_csv(OUTPUT / "kinematic_raw_audit.csv", index=False)
    pair_frame.to_csv(OUTPUT / "kinematic_impossible_pairs.csv", index=False)
    return audit, pair_frame


def moving_shared_destinations(raw: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    candidates = pd.read_csv(OUTPUT / "moving_track_audit.csv")
    candidates = candidates[candidates["passes_geometry"]].copy()
    refs = candidates.set_index(KEY)[["source_lat", "source_lon"]].to_dict("index")
    selected = raw.merge(candidates[KEY], on=KEY, how="inner")
    selected["identity"] = uid(selected)
    selected["source_lat"] = [refs[tuple(row)]["source_lat"] for row in selected[KEY].itertuples(index=False, name=None)]
    selected["source_lon"] = [refs[tuple(row)]["source_lon"] for row in selected[KEY].itertuples(index=False, name=None)]
    selected["distance_from_source_km"] = haversine(
        selected.lat, selected.lon, selected.source_lat, selected.source_lon
    )
    selected = selected[selected["distance_from_source_km"] >= 25].copy()
    selected["day"] = selected.timestamp.dt.floor("D")
    shared = selected.groupby(["day", "plat", "plon"]).agg(
        identities=("identity", "nunique"), distinct_cids=("cid", "nunique"),
        operators=("mnc", "nunique"), mccs=("mcc", "nunique"),
        source_lat_span=("source_lat", lambda x: x.max() - x.min()),
        source_lon_span=("source_lon", lambda x: x.max() - x.min()),
        observations=("identity", "size"), identity_list=("identity", lambda x: "|".join(sorted(set(x)))),
    ).reset_index()
    shared = shared[shared["identities"] >= 2].sort_values(
        ["identities", "day"], ascending=[False, True]
    )
    shared.to_csv(OUTPUT / "moving_shared_destination_days.csv", index=False)

    pair_counts: dict[tuple[str, str], int] = {}
    for identities in shared.identity_list:
        values = identities.split("|")
        for pair in itertools.combinations(values, 2):
            pair_counts[pair] = pair_counts.get(pair, 0) + 1
    pair_rows = [{"identity_a": a, "identity_b": b, "shared_destination_days": n}
                 for (a, b), n in pair_counts.items() if n >= 3]
    pair_frame = pd.DataFrame(
        pair_rows,
        columns=["identity_a", "identity_b", "shared_destination_days"],
    )
    if not pair_frame.empty:
        pair_frame = pair_frame.sort_values("shared_destination_days", ascending=False)
    pair_frame.to_csv(OUTPUT / "moving_shared_identity_pairs.csv", index=False)
    return shared, pair_frame


def validate_multidestination(raw: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    candidates = pd.read_csv(OUTPUT / "multidestination_identity_audit.csv")
    candidates = candidates[candidates["cycle_candidate"]].copy()
    refs = candidates.set_index(KEY)[["source_lat", "source_lon"]].to_dict("index")
    selected = raw.merge(candidates[KEY], on=KEY, how="inner")
    selected["identity"] = uid(selected)
    selected["source_lat"] = [refs[tuple(row)]["source_lat"] for row in selected[KEY].itertuples(index=False, name=None)]
    selected["source_lon"] = [refs[tuple(row)]["source_lon"] for row in selected[KEY].itertuples(index=False, name=None)]
    selected["distance_from_source_km"] = haversine(
        selected.lat, selected.lon, selected.source_lat, selected.source_lon
    )
    selected = selected[selected["distance_from_source_km"] >= 20].copy()
    audits, transitions = [], []
    for identity, group in selected.groupby("identity", sort=False):
        group = group.sort_values("timestamp")
        group = group.loc[group[["plat", "plon"]].ne(group[["plat", "plon"]].shift()).any(axis=1)]
        coords = list(zip(group.plat.astype(int), group.plon.astype(int), strict=True))
        cycle_count = 0
        for i in range(len(coords) - 2):
            for j in range(i + 2, len(coords)):
                if coords[i] == coords[j] and len(set(coords[i:j + 1])) >= 2:
                    cycle_count += 1
                    break
        for left, right in zip(group.iloc[:-1].itertuples(index=False), group.iloc[1:].itertuples(index=False)):
            transitions.append({
                "identity": identity, "mcc": left.mcc, "mnc": left.mnc,
                "transition_day": right.timestamp.floor("D"),
                "from_plat": left.plat, "from_plon": left.plon,
                "to_plat": right.plat, "to_plon": right.plon,
                "transition_hours": (right.timestamp - left.timestamp).total_seconds() / 3600,
            })
        first = group.iloc[0]
        audits.append({
            "identity": identity, "mcc": first.mcc, "mnc": first.mnc,
            "lac": first.lac, "cid": first.cid, "cell_type": first.cell_type,
            "raw_away_observations": len(group), "raw_destinations": len(set(coords)),
            "raw_return_cycles": cycle_count,
            "first_raw_destination": group.timestamp.min(),
            "last_raw_destination": group.timestamp.max(),
        })
    transition_frame = pd.DataFrame(transitions)
    if not transition_frame.empty:
        batches = transition_frame.groupby(
            ["transition_day", "from_plat", "from_plon", "to_plat", "to_plon"], as_index=False
        ).agg(
            identities=("identity", "nunique"), distinct_cids=("identity", "nunique"),
            operators=("mnc", "nunique"), mccs=("mcc", "nunique"),
            median_transition_hours=("transition_hours", "median"),
        )
        batches = batches[batches.identities >= 2].sort_values(
            ["identities", "transition_day"], ascending=[False, True]
        )
    else:
        batches = pd.DataFrame()
    audit = pd.DataFrame(audits)
    audit.to_csv(OUTPUT / "multidestination_raw_sequence_audit.csv", index=False)
    batches.to_csv(OUTPUT / "multidestination_shared_transitions.csv", index=False)
    return audit, batches


def event_tuples(frame: pd.DataFrame, columns: list[str]) -> str:
    values = []
    for row in frame[columns].drop_duplicates().itertuples(index=False, name=None):
        formatted = []
        for column, value in zip(columns, row, strict=True):
            if column == "onset_day":
                formatted.append(f"toDate('{pd.Timestamp(value).date()}')")
            else:
                formatted.append(str(int(value)))
        values.append("(" + ",".join(formatted) + ")")
    return ",".join(values)


