def audit_short_members(members: pd.DataFrame) -> pd.DataFrame:
    event_key = ["src_lat10", "src_lon10", "onset_day", "plat", "plon"]
    for column in ["first_seen", "last_seen", "home_first_month", "home_last_month"]:
        members[column] = pd.to_datetime(members[column])
    members["home_active_at_onset"] = (
        (members.home_first_month <= members.first_seen)
        & (members.home_last_month + pd.offsets.MonthEnd(0) >= members.first_seen)
    )
    members["home_after"] = members.home_last_month + pd.offsets.MonthEnd(0) > members.first_seen
    members["onset_hour"] = members.first_seen.dt.floor("h")
    rows = []
    for key, group in members.groupby(event_key, sort=False):
        hour_counts = group.groupby("onset_hour")[KEY].size()
        identities = group[KEY].drop_duplicates().shape[0]
        rows.append(dict(zip(event_key, key, strict=True)) | {
            "identities": identities, "distinct_cids": group.cid.nunique(),
            "operators": group[["mcc", "mnc"]].drop_duplicates().shape[0],
            "technologies": group.cell_type.nunique(), "observations": int(group.obs.sum()),
            "median_km": group.distance_km.median(),
            "first_onset": group.first_seen.min(), "last_onset": group.first_seen.max(),
            "onset_span_hours": (group.first_seen.max() - group.first_seen.min()).total_seconds() / 3600,
            "largest_onset_hour": hour_counts.idxmax(),
            "largest_onset_hour_fraction": hour_counts.max() / identities,
            "home_active_fraction": group.home_active_at_onset.mean(),
            "home_after_fraction": group.home_after.mean(),
            "median_reference_stability": group.stab_frac.median(),
        })
    audit = pd.DataFrame(rows)
    audit["synchronized_persistent_candidate"] = (
        audit.distinct_cids.ge(10)
        & ((audit.operators >= 2) | (audit.technologies >= 2))
        & audit.median_km.ge(10)
        & audit.largest_onset_hour_fraction.ge(0.8)
        & audit.home_active_fraction.ge(0.8)
        & audit.home_after_fraction.ge(0.8)
    )
    audit.sort_values(
        ["synchronized_persistent_candidate", "distinct_cids", "observations"], ascending=False
    ).to_csv(OUTPUT / "short_range_raw_member_audit.csv", index=False)
    members.to_csv(OUTPUT / "short_range_candidate_members.csv.gz", index=False, compression="gzip")
    return audit


