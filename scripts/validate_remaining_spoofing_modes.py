def audit_small_members(members: pd.DataFrame) -> pd.DataFrame:
    event_key = ["src_lat10", "src_lon10", "onset_day", "dest_lat5", "dest_lon5"]
    members["onset_ts"] = pd.to_datetime(members.onset_ts)
    rows = []
    for key, group in members.groupby(event_key, sort=False):
        identities = group[KEY].drop_duplicates()
        rows.append(dict(zip(event_key, key, strict=True)) | {
            "identities": len(identities), "distinct_cids": group.cid.nunique(),
            "operators": identities[["mcc", "mnc"]].drop_duplicates().shape[0],
            "technologies": group.cell_type.nunique(), "away_observations": int(group.away_obs.sum()),
            "first_onset": group.onset_ts.min(), "last_onset": group.onset_ts.max(),
            "onset_span_minutes": (group.onset_ts.max() - group.onset_ts.min()).total_seconds() / 60,
            "median_km": group.med_km.median(),
            "source_lat": group.rlat.median() / 100, "source_lon": group.rlon.median() / 100,
            "destination_lat": group.top_plat.median() / 100,
            "destination_lon": group.top_plon.median() / 100,
            "source_radius_p90_km": np.quantile(haversine(
                group.rlat / 100, group.rlon / 100, group.rlat.median() / 100, group.rlon.median() / 100
            ), .9),
            "destination_radius_p90_km": np.quantile(haversine(
                group.top_plat / 100, group.top_plon / 100,
                group.top_plat.median() / 100, group.top_plon.median() / 100
            ), .9),
        })
    audit = pd.DataFrame(rows)
    audit["tight_synchronized_candidate"] = (
        audit.distinct_cids.ge(2) & ((audit.operators >= 2) | (audit.technologies >= 2))
        & audit.onset_span_minutes.le(60) & audit.source_radius_p90_km.le(50)
        & audit.destination_radius_p90_km.le(5)
    )
    audit.sort_values(
        ["tight_synchronized_candidate", "distinct_cids", "away_observations"], ascending=False
    ).to_csv(OUTPUT / "small_cohort_raw_member_audit.csv", index=False)
    members.to_csv(OUTPUT / "small_cohort_candidate_members.csv", index=False)
    return audit


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh-raw", action="store_true")
    parser.add_argument("--refresh-event-members", action="store_true")
    parser.add_argument("--refresh-event-raw", action="store_true")
    args = parser.parse_args()
    OUTPUT.mkdir(parents=True, exist_ok=True)

    raw_path = OUTPUT / "raw_candidate_observations.csv.gz"
    if args.refresh_raw:
        raw = fetch_raw(candidate_identities())
        raw.to_csv(raw_path, index=False, compression="gzip")
    else:
        raw = pd.read_csv(raw_path, parse_dates=["timestamp"])
    validate_kinematics(raw)
    moving_shared_destinations(raw)
    validate_multidestination(raw)

    short_events = pd.read_csv(OUTPUT / "short_range_event_audit.csv", parse_dates=["onset_day"])
    short_events = short_events[short_events.high_signal]
    short_member_path = OUTPUT / "short_range_candidate_members.csv.gz"
    small_events = pd.read_csv(OUTPUT / "small_cohort_event_audit.csv", parse_dates=["onset_day"])
    small_events = small_events[small_events.coordinated_candidate]
    small_member_path = OUTPUT / "small_cohort_candidate_members.csv"
    if args.refresh_event_members:
        short_members = fetch_short_members(short_events)
        small_members = fetch_small_members(small_events)
    else:
        short_members = pd.read_csv(short_member_path)
        small_members = pd.read_csv(small_member_path)
    short_audit = audit_short_members(short_members)
    small_audit = audit_small_members(small_members)

    short_selected, small_selected = selected_event_members()
    event_raw_path = OUTPUT / "event_candidate_observations.csv.gz"
    if args.refresh_event_raw:
        event_ids = pd.concat([short_selected[KEY], small_selected[KEY]]).drop_duplicates()
        event_raw = fetch_raw(event_ids)
        event_raw.to_csv(event_raw_path, index=False, compression="gzip")
    elif event_raw_path.exists():
        event_raw = pd.read_csv(event_raw_path, parse_dates=["timestamp"])
    else:
        event_raw = None
    if event_raw is not None:
        raw_membership_pair_audit(
            event_raw, short_selected,
            ["src_lat10", "src_lon10", "onset_day", "plat", "plon"],
            "plat", "plon", 100, "short_range",
        )
        raw_membership_pair_audit(
            event_raw, small_selected,
            ["src_lat10", "src_lon10", "onset_day", "dest_lat5", "dest_lon5"],
            "top_plat", "top_plon", 100, "small_cohort",
        )
    print({
        "raw_observations": len(raw),
        "kinematic_targets": len(pd.read_csv(OUTPUT / "kinematic_raw_audit.csv")),
        "short_range_events_validated": len(short_audit),
        "small_cohort_events_validated": len(small_audit),
    })


if __name__ == "__main__":
    main()
